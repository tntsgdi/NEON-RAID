from build_r0 import DARKER, overlay, poly_mask, remap, shade  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..", "..", "assets", "sprites")
N = 32
KEY = {"7": "k7", "6": "k6", "5": "k5", "4": "k4", "3": "k3", "2": "k2", "1": "k1",
       "r": "r1", "R": "r2", "P": "r3", "W": "w0", "y": "y1", "Y": "y2"}
TO_CYAN = {"r0": "c0", "r1": "c1", "r2": "c2", "r3": "c3"}
TO_WHITE = {"r0": "k4", "r1": "k6", "r2": "k7", "r3": "w0"}


def save(unit, name, img, pivot, dark=False, wild=False):
    out = os.path.join(ROOT, unit)
    pix.atlas(img, pivot, N, name, out)
    pix.atlas(remap(img, TO_CYAN), pivot, N, name + "_p", out)
    if wild:
        pix.atlas(remap(img, TO_WHITE), pivot, N, name + "_w", out)
    if dark:
        d = remap(img, DARKER)
        pix.atlas(d, pivot, N, name + "_b", out)
        pix.atlas(remap(d, TO_CYAN), pivot, N, name + "_b_p", out)


def body(pts, w, h, details):
    img = shade(poly_mask(pts, w, h), [(0.2, "k6"), (0.55, "k5"), (0.85, "k4"), (1.0, "k4")])
    return overlay(img, details, KEY)


